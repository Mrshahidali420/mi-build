/**
 * Writes public/lv-init.js: the Linkvertise set-up for the official read and
 * watch platform links (owner decision, 23 Oct 2026: the site costs money to
 * run and earns nothing, so platform links are monetised; Amazon links never).
 *
 * Linkvertise's script rewrites every <a href> whose address matches the
 * whitelist, once, on DOMContentLoaded. A pattern without "*" matches anywhere
 * in the address, so each platform is pinned to its own host
 * ("https://*webtoons.com*"), and the blacklist, checked first, keeps every
 * Amazon address out whatever else matches.
 *
 * The host list is read from the catalog on every build, so a new platform is
 * covered by the next deploy. Before the rewrite, the real address is copied to
 * data-dest, so our click counter still records where a reader was going.
 *
 *   node scripts/make-linkvertise.mjs
 */
import { readFileSync, writeFileSync } from 'fs'
import { join } from 'path'

export const LINKVERTISE_ID = 10316435
const DATA = 'data'
const OUT = join('public', 'lv-init.js')
const NEVER = /(^|\.)(amazon|amzn)\./

const read = (name) => {
  try { return JSON.parse(readFileSync(join(DATA, name), 'utf8')) } catch { return [] }
}

/** Every platform host in the catalog's read and watch links, Amazon left out. */
export function platformHosts(titles) {
  const hosts = new Set()
  for (const t of titles) {
    for (const link of [...(t.readLinks || []), ...(t.watchLinks || [])]) {
      try {
        const host = new URL(link.url).hostname.replace(/^www\./, '')
        if (!NEVER.test(host)) hosts.add(host)
      } catch {}
    }
  }
  return [...hosts].sort()
}

/**
 * A pattern that matches one host and its subdomains, and nothing else.
 *
 * Linkvertise turns a pattern into a regex by replacing "*" with ".*" and
 * escaping nothing, and a pattern with no "*" matches anywhere. So the first
 * version, "https://*x.com*", also matched "https://manhwaindex.com/..." and
 * rewrote our own links (23 Oct 2026). This one is a real regex: the host
 * starts the address or follows a dot, its dots are literal, and only a path
 * may follow. The one "*" (in "(/*)") keeps Linkvertise from wrapping it.
 */
export function hostPattern(host) {
  const exact = host.replace(/[.+?^${}()|[\]\\]/g, '\\$&')
  return `https://([^/]+\\.)?${exact}(/*)?`
}

export function initScript(hosts) {
  // An empty whitelist means "every outside link" to Linkvertise: never send one.
  if (!hosts.length) return '// Generated by scripts/make-linkvertise.mjs: no platform hosts, Linkvertise off.\n'
  const whitelist = hosts.map(hostPattern)
  const blacklist = [hostPattern('manhwaindex.com'), '*amazon.*', '*amzn.*', '*amazon-adsystem*']
  return `// Generated by scripts/make-linkvertise.mjs. Do not edit.
// Runs (deferred) before DOMContentLoaded, when Linkvertise rewrites links.
document.querySelectorAll('a[data-go][href^="http"]').forEach(function (a) { a.setAttribute('data-dest', a.href) })
if (typeof linkvertise === 'function') linkvertise(${LINKVERTISE_ID}, { whitelist: ${JSON.stringify(whitelist)}, blacklist: ${JSON.stringify(blacklist)} })
`
}

if (import.meta.url === `file://${process.argv[1].replace(/\\/g, '/')}` || process.argv[1]?.endsWith('make-linkvertise.mjs')) {
  const hosts = platformHosts([...read('comics.json'), ...read('anime.json')])
  writeFileSync(OUT, initScript(hosts))
  console.log(`lv-init.js: ${hosts.length} platform hosts monetised, Amazon excluded`)
}
